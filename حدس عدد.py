import matplotlib.pyplot as plt
import random
import math

# --- ۱. تعریف مختصات سه راس مثلث ---
# راس R (پایین چپ)
x_R = 0.0
y_R = 0.0

# راس G (پایین راست)
x_G = 1.0
y_G = 0.0

# راس B (بالا)
x_B = 0.5
y_B = math.sqrt(3) / 2  # جذر ۳ تقسیم بر ۲

# --- ۲. آماده‌سازی برای ذخیره نقاط ---
# دو لیست خالی می‌سازیم تا مختصات X و Y نقاطی که رسم می‌کنیم را در آن‌ها نگه داریم
list_x = []
list_y = []

# --- ۳. نقطه شروع بازی ---
# بازی از راس R شروع می‌شود
x = x_R
y = y_R

# --- ۴. تعداد تکرار بازی ---
n = 10000 # هرچه این عدد بزرگتر باشد، شکل واضح‌تر می‌شود (مثلا 50000)

# --- ۵. شروع حلقه بازی ---
for i in range(n):
    # یک عدد تصادفی ۱، ۲ یا ۳ انتخاب می‌کنیم
    # ۱ یعنی برو به سمت R
    # ۲ یعنی برو به سمت G
    # ۳ یعنی برو به سمت B
    random_number = random.randint(1, 3)
    
    # محاسبه نقطه جدید (حرکت به اندازه نصف فاصله تا راس انتخاب شده)
    if random_number == 1:
        # حرکت به سمت R
        x = (x + x_R) / 2
        y = (y + y_R) / 2
        
    elif random_number == 2:
        # حرکت به سمت G
        x = (x + x_G) / 2
        y = (y + y_G) / 2
        
    else:
        # حرکت به سمت B
        x = (x + x_B) / 2
        y = (y + y_B) / 2
        
    # حالا که نقطه جدید را پیدا کردیم، آن را به لیست‌ها اضافه می‌کنیم
    list_x.append(x)
    list_y.append(y)

# --- ۶. رسم نمودار ---
# یک صفحه برای رسم آماده می‌کنیم
plt.figure(figsize=(8, 7))

# نقاط را رسم می‌کنیم. s=1 یعنی اندازه نقطه‌ها خیلی کوچک باشد
plt.scatter(list_x, list_y, s=1, color='blue')

# این خط باعث می‌شود شکل مثلث ما کشیده یا فشرده نشود (نسبت ابعاد ۱ به ۱)
plt.axis('equal')

# گذاشتن عنوان برای نمودار
plt.title('Sierpinski Triangle - Chaos Game')

# نمایش نمودار
plt.show()